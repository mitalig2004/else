import assert from 'node:assert/strict';
import {fixture,parseCurrency} from '../dist/model.mjs';
import {defaultCollaboration,collaborationTotal,collaborationTransition as change,publicGoal,loadCollaboration} from '../dist/collaboration-model.mjs';
let c=defaultCollaboration();
assert.equal(collaborationTotal(c),18000);
c=change(c,'INVITE_SENT',{email:'rohan@example.com',permission:'view'});
assert.equal(c.status,'INVITE_SENT');
assert.throws(()=>change(c,'CONTRIBUTION',{amount:2000}));
c=change(c,'ACCEPTED');
assert.throws(()=>change(c,'NOTE',{actor:'rohan',note:'Not allowed'}));
assert.throws(()=>change(c,'CONTRIBUTION',{amount:2000}));
c=change(c,'PERMISSION',{permission:'contribute'});
c=change(c,'NOTE',{actor:'rohan',note:'Flights first, hotel next.'});
c=change(c,'CONTRIBUTION',{amount:2000});
assert.equal(collaborationTotal(c),20000);
assert.equal(fixture.balance,42800);
assert.throws(()=>change(c,'CONTRIBUTION',{amount:10001}));
assert.throws(()=>change(c,'CONTRIBUTION',{amount:0}));
const snapshot=publicGoal({contribution:5100,previous:{contribution:8000},salary:85000,balance:42800,transactions:['private'],buffer:7000},c);
assert.deepEqual(Object.keys(snapshot).sort(),['name','target','saved','contributions','plannedContribution','estimatedCompletion','note','status','permission','events','planChange'].sort());
assert.equal(snapshot.contributions.reduce((n,p)=>n+p.saved,0),snapshot.saved);
assert.equal(snapshot.estimatedCompletion,'Nov 20');
assert.deepEqual(snapshot.planChange,{before:8000,after:5100});
for(const privateValue of ['85000','42800','transactions','salary','buffer'])assert.equal(JSON.stringify(snapshot).includes(privateValue),false);
c=change(c,'REMOVED');
assert.throws(()=>change(c,'CONTRIBUTION',{amount:1}));
assert.equal(collaborationTotal(c),20000);
assert.deepEqual(loadCollaboration({getItem:()=>'{bad'}),defaultCollaboration());
for(const value of ['12000','12,000','₹12,000',' ₹ 12,000 '])assert.equal(parseCurrency(value),12000);
for(const value of ['','-1','12.5','abc','1e3'])assert.equal(Number.isNaN(parseCurrency(value)),true);
console.log('Shared-goal permissions, privacy allowlist, persistence fallback and currency checks passed.');
